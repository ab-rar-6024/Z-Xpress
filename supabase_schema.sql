-- ---------- app_users (login accounts) ----------
create table if not exists app_users (
    id          integer generated by default as identity primary key,
    username    varchar(100) not null,
    password    varchar(255) not null,
    role        varchar(10)  not null default 'user' check (role in ('admin','user')),
    created_at  timestamptz  not null default now()
);

-- MySQL compared usernames case-insensitively; keep that (db.py also
-- rewrites  username = %s  to  LOWER(username) = LOWER(%s)).
create unique index if not exists uq_app_users_username_ci on app_users (lower(username));

-- ---------- bookings ----------
create table if not exists bookings (
    id            integer generated by default as identity primary key,
    code          varchar(20),
    code_fullform varchar(255),
    booking_date  date,
    awb_no        varchar(50),
    destination   varchar(100),
    weight        numeric(10,3),
    courier       varchar(100),
    zone          varchar(100),
    auto_amount   numeric(12,2),
    fuel          numeric(12,2),
    total_amount  numeric(12,2),
    gst_18pct     numeric(12,2),
    net_total     numeric(12,2),
    month         varchar(20),
    client_name   varchar(255),
    inv_no        varchar(50),
    inv_date      date
);
create index if not exists idx_bookings_awb_no       on bookings (awb_no);
create index if not exists idx_bookings_booking_date on bookings (booking_date);
create index if not exists idx_bookings_code         on bookings (code);

-- ---------- day_wise ----------
create table if not exists day_wise (
    id           integer generated by default as identity primary key,
    entry_date   date,
    total_weight numeric(10,3),
    total_sales  numeric(10,2)
);

-- ---------- license ----------
create table if not exists license (
    id          integer generated by default as identity primary key,
    license_key varchar(100) not null,
    expiry_date date         not null,
    created_at  timestamptz  not null default now()
);

-- ---------- place_zones ----------
create table if not exists place_zones (
    id         integer generated by default as identity primary key,
    place      varchar(100) not null unique,
    zone       smallint     not null,
    place_code varchar(20)
);
create index if not exists idx_place_zones_code on place_zones (place_code);

-- ---------- rates ----------
create table if not exists rates (
    id              integer generated by default as identity primary key,
    code            varchar(10) not null,
    code_fullform   varchar(200),
    place           varchar(100),
    zone            smallint default 5,
    rate_250g       numeric(10,2),
    rate_500g       numeric(10,2),
    rate_500g_1     numeric(10,2),
    rate_1_to_3kg   numeric(10,2),
    rate_3_to_10kg  numeric(10,2),
    rate_above_10kg numeric(10,2),
    fuel            numeric(10,2)
);
create index if not exists idx_rates_code       on rates (code);
create index if not exists idx_rates_code_place on rates (code, place);

-- ---------- users (legacy table) ----------
create table if not exists users (
    id       integer generated by default as identity primary key,
    username varchar(100) not null,
    password varchar(100) not null
);

-- ---------- zones (district -> rate zone) ----------
create table if not exists zones (
    id        integer generated by default as identity primary key,
    district  varchar(100),
    rate_zone varchar(50)
);
create index if not exists idx_zones_district on zones (district);

-- ============================================================
-- SECURITY
-- Supabase publishes every table in `public` through its REST API using the
-- public "anon" key.  Turning RLS on with NO policies blocks that API
-- completely, while the app's own direct database connection (postgres role)
-- keeps full access.  Do not add permissive policies to these tables.
-- ============================================================
alter table app_users   enable row level security;
alter table bookings    enable row level security;
alter table day_wise    enable row level security;
alter table license     enable row level security;
alter table place_zones enable row level security;
alter table rates       enable row level security;
alter table users       enable row level security;
alter table zones       enable row level security;
